#!/usr/bin/env python3
"""Check every relative link in the repository's Markdown.

This repo is mostly documentation, and it is documentation that points at itself:
five edition directories, each with its own README, docs, plugin skill and
reference files, all cross-linking to the root and to each other. Moving or
renaming a file breaks those links silently -- nothing fails, the link just stops
resolving, and the next reader finds a 404 instead of the contract they were sent
to read.

Only relative links are checked. External URLs are left to a human: this must
stay offline and deterministic so it can sit inside the canonical gate.

    python tools/check_links.py
"""

from __future__ import annotations

import os
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import unquote

ROOT = Path(__file__).resolve().parent.parent

LINK_PATTERN = re.compile(r"(?<!!)\[[^\]]*\]\(([^)]+)\)")
IMAGE_PATTERN = re.compile(r"!\[[^\]]*\]\(([^)]+)\)")
HTML_SRC_PATTERN = re.compile(r"""(?is)<img[^>]+src=["']([^"']+)["']""")

SKIP_PREFIXES = ("http://", "https://", "mailto:", "tel:", "#", "$")

# Generated by the scheduled checks into the workspace, never committed.
SKIP_NAMES = {
    "upstream-review-report.md",
    "dependency-freshness-report.md",
}


def iter_documents() -> list[Path]:
    """Every tracked or non-ignored new Markdown file.

    `git ls-files` rather than a glob: it inherits `.gitignore`, so a local
    ignored scratch file stays outside the gate; new source docs are checked.
    """
    result = subprocess.run(
        ["git", "-C", str(ROOT), "ls-files", "--cached", "--others", "--exclude-standard", "*.md"],
        capture_output=True,
        text=True,
        encoding="utf-8",
        check=False,
    )
    if result.returncode != 0:
        return sorted(
            path for path in ROOT.rglob("*.md") if ".git" not in path.parts
        )
    return sorted(
        ROOT / line
        for line in result.stdout.splitlines()
        if line and Path(line).name not in SKIP_NAMES
    )


def check_casing(base: Path, file_part: str) -> tuple[bool, str | None]:
    """Check whether every component of file_part exists with exact casing.

    Returns (True, actual_path) if every part matches exactly,
    (False, actual_path) if the target exists but has a case mismatch,
    or (False, None) if the target does not exist.
    """
    cur = base.resolve()
    rel_path = Path(file_part.replace("\\", "/"))
    if rel_path.is_absolute():
        cur = Path(cur.anchor)
        parts = rel_path.parts[1:]
    else:
        parts = rel_path.parts

    if not parts:
        return (base / file_part).resolve().exists(), ""

    actual_parts: list[str] = []
    has_mismatch = False

    for part in parts:
        if part in (".", ""):
            continue
        if part == "..":
            actual_parts.append("..")
            cur = cur.parent
            continue
        try:
            entries = os.listdir(cur)
        except OSError:
            return False, None
        if part in entries:
            actual_parts.append(part)
            cur = cur / part
        else:
            lower_map = {e.lower(): e for e in entries}
            if part.lower() in lower_map:
                has_mismatch = True
                actual_name = lower_map[part.lower()]
                actual_parts.append(actual_name)
                cur = cur / actual_name
            else:
                return False, None

    actual = "/".join(actual_parts)
    return (not has_mismatch), actual


def check_case_mismatch(base: Path, file_part: str, target: str) -> str | None:
    """Check if any path segment in file_part has a case mismatch on disk."""
    match, actual = check_casing(base, file_part)
    if not match and actual is not None:
        detail = f" (on disk: '{actual}')" if actual else ""
        return f"{target} -> case mismatch{detail}"
    return None


def missing_target(path: Path, target: str) -> str | None:
    """Return a description of the broken link, or None when it resolves."""
    target = target.strip().strip("<>")
    if not target or target.startswith(SKIP_PREFIXES):
        return None
    # A link may carry a title: [text](./file.md "Title").
    file_part = unquote(target.split()[0].split("#", 1)[0])
    if not file_part:
        return None
    match, actual = check_casing(path.parent, file_part)
    if match:
        return None
    if actual is not None:
        detail = f" (on disk: '{actual}')" if actual else ""
        return f"{target} -> case mismatch{detail}"
    resolved = (path.parent / file_part).resolve()
    try:
        shown = resolved.relative_to(ROOT)
    except ValueError:
        shown = resolved
    return f"{target} -> missing {shown}"


def check_document(path: Path) -> list[str]:
    problems: list[str] = []
    text = path.read_text(encoding="utf-8")
    for pattern in (LINK_PATTERN, IMAGE_PATTERN, HTML_SRC_PATTERN):
        for match in pattern.finditer(text):
            problem = missing_target(path, match.group(1))
            if problem:
                problems.append(problem)
    return problems


def main() -> int:
    documents = iter_documents()
    if not documents:
        print("FAIL: no Markdown source files were found")
        return 1

    failures = 0
    for path in documents:
        relative = path.relative_to(ROOT)
        problems = check_document(path)
        if problems:
            failures += 1
            for problem in problems:
                print(f"FAIL {relative}: {problem}")
        else:
            print(f"OK   {relative}")

    print(f"\n{len(documents)} Markdown files checked, {failures} with broken links.")
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
